const assert = require('node:assert/strict');
const { spawn } = require('node:child_process');
const { chromium } = require('playwright');

(async () => {
  const server = spawn(process.env.TEST_PYTHON, ['tests/classroom_ui_server.py'], { stdio: ['pipe', 'pipe', 'pipe'] });
  let log = '', browser;
  server.stderr.on('data', chunk => log += chunk);
  const base = await new Promise((resolve, reject) => {
    server.stdout.on('data', chunk => { if (String(chunk).startsWith('http://')) resolve(String(chunk).trim()); });
    server.on('exit', code => reject(Error('Server exited ' + code + log)));
  });
  try {
    browser = await chromium.launch({ headless: true, channel: 'msedge' });
    const student = await browser.newContext(), teacher = await browser.newContext();
    await student.request.post(base + '/api/login', { data: { role: 'student', classId: 'default', groupId: 1, studentCode: '9512' } });
    await teacher.request.post(base + '/api/login', { data: { role: 'teacher', username: 'ui_teacher', password: 'ClassroomTeacher#2026' } });
    const p = await student.newPage(), t = await teacher.newPage(), errors = [];
    for (const page of [p,t]) page.on('pageerror', error => errors.push(error.message));
    await p.goto(base + '/student/stage1.html');
    await p.locator('#submitStage').click();
    await p.locator('#reopenStage').waitFor();
    await p.locator('#reopenStage').click();
    await p.locator('#submitStage:not([disabled])').waitFor();
    await p.goto(base + '/student/group.html');
    await p.locator('[data-role-index="0"]').waitFor();
    assert.equal(await p.locator('[data-role-index="0"] option').count(), 4);
    await p.locator('[data-role-index="0"]').selectOption('解释者');
    assert((await p.locator('[data-role-duty="0"]').innerText()).length > 0);
    await p.goto(base + '/student/stage3-model.html');
    await p.locator('[data-quantity]').first().waitFor();
    assert.equal(await p.locator('[data-quantity]').count(), 5);
    await p.locator('#addQuantity').click();
    assert.equal(await p.locator('[data-quantity]').count(), 10);
    await p.locator('[data-quantity="name"]').nth(1).fill('宽度');
    await p.locator('[data-quantity="unit"]').nth(1).fill('米');
    await p.reload();
    await p.locator('[data-quantity="name"]').nth(1).waitFor();
    assert.equal(await p.locator('[data-quantity="name"]').nth(1).inputValue(),'宽度');
    assert.equal(await p.locator('[data-quantity="unit"]').nth(1).inputValue(),'米');
    await p.goto(base + '/student/stage2-question-tree.html');
    await p.locator('#addQuestion').click();
    await p.locator('[data-question-row]').first().fill('需要测量哪些边长？');
    await p.locator('[data-question-link]').first().selectOption('stage3-graph.html');
    await p.reload();
    await p.locator('[data-question-row]').first().waitFor();
    assert.equal(await p.locator('[data-question-row]').first().inputValue(),'需要测量哪些边长？');
    const questionSave=p.waitForResponse(response=>response.url().endsWith('/api/state')&&response.request().method()==='PUT');
    await p.locator('#saveQuestions').click();
    const questionResult=await questionSave;
    assert.equal(questionResult.status(),200,JSON.stringify(await questionResult.json()));
    await p.goto(base + '/student/stage4-discussion.html');
    await p.locator('#skipDiscussion').check();
    await p.locator('#saveDiscussion').click();
    await p.getByText('没有不同意见，跳过本项', {exact:true}).last().waitFor();
    await p.goto(base + '/student/stage4-evidence.html');
    await p.locator('#newRecord').click();
    await p.locator('#recordText').fill('测量结果为8厘米');
    await p.locator('#saveRecord').click();
    await p.locator('[data-edit-record]').first().waitFor();
    await p.locator('[data-edit-record]').first().click();
    await p.locator('#recordVerified').check();
    await p.locator('#saveRecord').click();
    await p.getByText('阶段4', {exact:false}).first().waitFor();
    await t.goto(base + '/teacher/evaluation.html?g=1');
    await t.locator('#evaluationComment').fill('尚未保存的评价内容');
    await t.locator('#evaluationEvidenceLink').click();
    await t.getByRole('link', {name:'返回该组评价'}).click();
    await t.locator('#evaluationComment').waitFor();
    assert.equal(await t.locator('#evaluationComment').inputValue(), '尚未保存的评价内容');
    await t.goto(base + '/teacher/project.html');
    await t.locator('#fieldConfiguration').waitFor();
    const row = t.locator('[data-config-id="under-problem"]');
    await row.locator('summary').click();
    await row.locator('[data-field-setting="title"]').fill('这次要回答的问题');
    await row.locator('[data-field-setting="type"]').selectOption('radio');
    await row.locator('[data-field-setting="options"]').fill('长度|面积');
    await row.locator('[data-field-setting="hint"]').fill('先看看需要比较哪一种量。');
    await t.locator('#fieldStage').selectOption('2');
    await t.locator('#previewStudentPage').click();
    const preview = t.frameLocator('iframe[title="学生页面预览"]');
    await preview.locator('[data-choice-for="under-problem"]').waitFor();
    assert((await preview.locator('label[for="under-problem"]').innerText()).includes('这次要回答的问题'));
    await preview.locator('[data-choice-for="under-problem"] input[value="面积"]').check();
    assert.equal(await preview.locator('#under-problem').inputValue(),'面积');
    await preview.locator('#saveUnderstandingNew').click();
    const beforePreviewSave=(await (await teacher.request.get(base+'/api/state?group=1')).json()).state;
    assert.notEqual(beforePreviewSave.workspace.problem,'面积');
    await t.locator('.modal [data-close]').click();
    await t.locator('#saveFieldsConfig').click();
    await t.getByText('填写模板已保存', {exact:true}).waitFor();
    const savedConfig = (await (await teacher.request.get(base + '/api/state')).json()).state.teacherConfig.fieldRules;
    assert.equal(savedConfig['under-known'].title, '题目给出的信息');
    assert.equal(savedConfig['under-unknown'].required, false);
    await p.goto(base + '/student/stage2-understanding.html');
    assert((await p.locator('label[for="under-problem"]').innerText()).includes('这次要回答的问题'));
    await p.locator('[data-choice-for="under-problem"] input[value="面积"]').check();
    assert.equal(await p.locator('#under-problem').inputValue(),'面积');
    const helper=p.locator('[data-field-help="under-problem"]');
    await helper.click();
    await p.locator('#aiPrompt').waitFor();
    assert((await p.locator('#aiPrompt').inputValue()).includes('已有内容：面积'));
    await p.goto(base + '/student/stage5-reflection.html');
    await p.locator('#reflect-changed').waitFor();
    assert.equal(await p.locator('[id^="reflect-"]').count(), 6);
    await p.goto(base+'/student/governance.html');
    await p.locator('#historyStage').waitFor();
    await p.locator('#historyStage').selectOption('2');
    const queueResult=await student.request.post(base+'/api/hints',{data:{action:'teacher',issue:'隐私求助内容',newThread:true,requestId:'ui-queue'}});
    assert(queueResult.ok(),await queueResult.text());
    await t.goto(base+'/teacher/queue.html');
    await t.locator('[data-help-response]').first().click();
    await t.locator('#responseHandling').selectOption('processing');
    await t.locator('#saveResponse').click();
    await t.locator('.modal-mask').waitFor({state:'detached'});
    const queueState=(await (await student.request.get(base+'/api/state')).json()).state;
    assert.equal(queueState.queue.at(-1).handling,'processing');
    await t.goto(base+'/teacher/queue.html?display=1');
    assert(!(await t.locator('body').innerText()).includes('隐私求助内容'));
    assert.equal(await t.locator('.topbar').count(),0);
    const exported = await teacher.request.get(base + '/api/export?format=xlsx');
    assert(exported.ok());
    assert((await exported.body()).length > 1000);
    assert.deepEqual(errors, []);
    console.log('DBR browser checks passed');
  } finally {
    if (browser) await browser.close();
    server.stdin.end();
  }
})().catch(error => { console.error(error); process.exitCode = 1; });
